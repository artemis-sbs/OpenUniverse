        for ship in live.values():
            self.fn("ship_set_cell")(ship.id, 1, -1)
        self.assertEqual(self.fn("universe_saved_cells")(), [[live["Intrepid"].id, 3, -2]])
        # ...and once it has moved her there, there is nothing left to do.
        self.fn("ship_set_cell")(live["Intrepid"].id, 3, -2)
        self.assertEqual(self.fn("universe_saved_cells")(), [])

