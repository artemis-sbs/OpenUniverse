class Evenings(SaveHarness):
    """Whole evenings: launch, ships, open the save, grant the story from a universe
    file, restore, save. `self.file` is the universe file tonight."""

    file = None

    def evening(self, story=None, mode="Continue", ships=("Artemis",)):
        self.launch()
        live = {}
        for spec in ships:
            name, side = spec if isinstance(spec, tuple) else (spec, "tsn")
            live[name] = self.ship(name, side)
        saved = self.begin(mode)
        self.finish(mode, saved, story=story if story is not None else self.file)
        self.live = live
        return live

    def save(self):
        self.assertTrue(self.fn("universe_save_players")())
        return self.fn("universe_load")()

    def state(self, key):
        return quest_get_state(Agent.SHARED_ID, key)

    def seconds(self, n):
        mock_sbs.sim._time_tick_counter += int(n * 30)


