    def test_GAP_13_each_ship_is_put_back_in_its_own_system(self):
        live = self.evening(mode="New Game", ships=("Artemis", "Intrepid"))
        self.fn("ship_set_cell")(live["Artemis"].id, 1, -1)
        self.fn("ship_set_cell")(live["Intrepid"].id, 3, -2)
        self.fn("universe_save")(7, 1, -1, {})       # the last jumper was Artemis
        self.save()
        live = self.evening(ships=("Artemis", "Intrepid"))
