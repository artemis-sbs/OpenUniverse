def quest_states(tree, _prefix=""):
    """`{path: (state, progress)}` for a saved quest tree, whichever way it was written."""
    out = {}
    for key, rec in (tree or {}).items():
        out[_prefix + key] = (rec.get("state", 0), rec.get("progress", 0) or 0)
        out.update(quest_states(rec.get("children"), _prefix + key + "/"))
    return out


