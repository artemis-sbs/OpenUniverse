def without_record(text, key):
    """A universe file with one `### [..](key)` record taken out."""
    lines = text.split("\n")
    start = next(i for i, l in enumerate(lines)
                 if l.startswith("#") and l.rstrip().endswith("(" + key + ")"))
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("#")),
               len(lines))
    return "\n".join(lines[:start] + lines[end:])


def with_field(text, key, line):
    """A universe file with one more fence line on the record keyed `key`."""
    lines = text.split("\n")
    start = next(i for i, l in enumerate(lines)
                 if l.startswith("#") and l.rstrip().endswith("(" + key + ")"))
    fence = next(i for i in range(start + 1, len(lines)) if lines[i].strip() == "---")
    return "\n".join(lines[:fence + 1] + [line] + lines[fence + 1:])


def _read_bytes(path):
    with open(path, "rb") as f:
        return f.read()


def players_by_name(data):
    """The ship records of a save, keyed by the ship's NAME - whichever version wrote
    it. Version 1 keyed `players` by name; version 2 keys it by a stable id and holds
    the name inside the record."""
    out = {}
    for key, rec in (data.get("players") or {}).items():
        out[rec.get("name", key) if isinstance(rec, dict) else key] = rec
    return out


class SaveHarness(unittest.TestCase):
    """The mission's Python, loaded once per class into its own namespace, with the
    saves folder pointed at a temp directory."""

    @classmethod
    def setUpClass(cls):
        cls.root = tempfile.mkdtemp(prefix="ou_save_test_")
        cls.mission = os.path.join(cls.root, "mission")
        os.makedirs(cls.mission)
        cls.old_script_dir = fs.script_dir
        # common_data is the mission folder's SIBLING, so this is what moves the saves.
        fs.script_dir = cls.mission
        cls.old_globals = dict(MastGlobals.globals)
        story = MastStory()
        story.basedir = OU_CORE
        # universe_amd / universe_doc: the universe's own reader, so a test grants a
        # story from the same parse universe_map_begin grants it from.
        cls.errors = story.compile("import universe_helpers.py\nimport universe_amd.py\n"
                                   "import universe_doc.py\n", "save_harness", story)
        cls.story = story

    @classmethod
    def tearDownClass(cls):
        MastGlobals.globals.clear()
        MastGlobals.globals.update(cls.old_globals)
        fs.script_dir = cls.old_script_dir
        shutil.rmtree(cls.root, ignore_errors=True)

    def setUp(self):
        self.assertEqual(self.errors, [])
        shutil.rmtree(os.path.join(self.root, "common_data"), ignore_errors=True)
        self.launch()

    def launch(self):
        """A fresh process as far as the game can tell: a new sim, no ships, no shared
        state - and whatever is in the saves folder still there. A test that plays two
        evenings calls this between them."""
        fs.script_dir = self.mission
        # The library's own per-mission reset, which is what a new process amounts to
        # for everything the LIBRARY keeps (facts, a ruin's ledger, quest timers).
        reset_mission_state()
        fs.script_dir = self.mission
        mock_sbs.create_new_sim()
        mock_sbs.resume_sim()
        SpaceObject.clear()
        clear_shared()
        FrameContext.context = Context(mock_sbs.sim, mock_sbs, FakeEvent(0, "test"))
        FrameContext.page = None
        Agent.SHARED.set_inventory_value("sim", mock_sbs.sim)
        reset = MastGlobals.globals.get("universe_save_reset")
        if reset is not None:
            reset()
        self.fn("universe_set_active_save")("Round Trip", 1)
        self.path = self.fn("universe_save_path")()
        # A test that resolves the real saves folder is a defect, so say so before
        # anything is written.
        inside = os.path.normcase(os.path.abspath(self.path)).startswith(
            os.path.normcase(os.path.abspath(self.root)))
        self.assertTrue(inside, "the save path left the temp folder: " + self.path)

    def tearDown(self):
        FrameContext.context = None

    def fn(self, name):
        return MastGlobals.globals[name]

    def module_globals(self):
        """universe_helpers.py's own namespace - where its private names live."""
        return self.fn("universe_save_players").__globals__

    def install(self, fixture):
        """Put a copy of a fixture where the active save is read from."""
        os.makedirs(os.path.dirname(self.path), exist_ok=True)
        shutil.copyfile(os.path.join(FIXTURES, fixture), self.path)
        return _read_bytes(self.path)

    def write_save(self, text):
        os.makedirs(os.path.dirname(self.path), exist_ok=True)
        with open(self.path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        return _read_bytes(self.path)

    def ship(self, name, side="tsn"):
        side_ensure(side)
        return player_spawn(0, 0, 0, name, side, "tsn_light_cruiser").py_object

    def files(self):
        folder = os.path.dirname(self.path)
        return sorted(os.listdir(folder)) if os.path.isdir(folder) else []

    def begin(self, mode):
        """What universe_map_begin does with the save before anything is spawned."""
        return self.fn("universe_save_begin")(mode)

    def grant(self, text):
        """Grant a universe file's story the way universe_map_begin does: the narrative
        and then the goals, each stamped as the file's own."""
        doc = self.fn("universe_doc")(text)
        for section in ("narrative", "goals"):
            node = self.fn("universe_section")(doc, section)
            quest_grant_amd(Agent.SHARED_ID, node)
            self.stamp(node)

    def stamp(self, node):
        # (Looked up, not called by name: run against a build from before the stamp
        # existed, the tests should fail for what that build DOES, not for a NameError.)
        stamp = MastGlobals.globals.get("universe_story_stamp")
        if stamp is not None:
            stamp(Agent.SHARED_ID, node)

    def grant_what_the_save_holds(self, saved):
        """"The universe file still has every step": grant the story steps a save holds,
        from the save's own copy of them. For a fixture whose universe file is not in
        this repo, and for the tests that are not about the file changing."""
        def authored(rec):
            data = rec.get("data")
            return (rec.get("authored") or "display_text" not in rec
                    or (isinstance(data, dict) and "scope" in data))

        def as_doc(tree):
            kids = []
            for key, rec in (tree or {}).items():
                if not authored(rec):
                    continue
                kids.append({"key": key, "display_text": rec.get("display_text", key),
                             "description": rec.get("description", ""),
                             "data": copy.deepcopy(rec.get("data")) or {},
                             "children": as_doc(rec.get("children"))["children"]})
            return {"children": kids}
        doc = as_doc((saved or {}).get("shared_quests"))
        quest_grant_amd(Agent.SHARED_ID, doc)
        self.stamp(doc)

    def finish(self, mode, saved, seed=7, story=None):
        """...and what it does once the ships exist. `story` is the universe file's
        text; without one the story is whatever the save holds."""
        if saved is None:
            self.fn("universe_save")(seed, 0, 0, {})
        else:
            cur = saved.get("current_system", [0, 0])
            self.fn("universe_save")(saved.get("universe_seed", 1), cur[0], cur[1],
                                     saved.get("systems", {}))
        if story is not None:
            self.grant(story)
        else:
            self.grant_what_the_save_holds(saved)
        self.fn("universe_load_players")(mode == "Continue")
        self.fn("universe_save_ready")()
        self.fn("universe_save_players")()


class RoundTrip(SaveHarness):
    """Load, restore onto ships, save, load again: nothing is lost and nothing moves."""

    def round_trip(self, fixture):
        self.install(fixture)
        before = copy.deepcopy(self.fn("universe_load")())
        self.assertIsNotNone(before)
        ships = {name: self.ship(name) for name in players_by_name(before)}
        saved = self.begin("Continue")
        self.assertIsNotNone(saved)
        self.finish("Continue", saved)
        after = self.fn("universe_load")()
        return before, after, ships

    def assert_same_campaign(self, before, after):
        for key in ("universe_seed", "current_system", "systems", "side_credits",
                    "side_admiralty"):
            self.assertEqual(after.get(key), before.get(key), key)
        # Every step and every job, in the state it was in. (A story step is saved slim
        # now - its state, not its text - so the records are compared by what they SAY.)
        self.assertEqual(quest_states(after.get("shared_quests")),
                         quest_states(before.get("shared_quests")))
        self.assertNotIn("parked_quests", after, "the file still has every step")
        was, now = players_by_name(before), players_by_name(after)
        self.assertEqual(sorted(now), sorted(was))
        for name, rec in was.items():
            for field in ("items", "installs", "quests", "reputation"):
                self.assertEqual(now[name].get(field), rec.get(field), f"{name}.{field}")

    def test_the_default_universe_comes_back_whole(self):
        before, after, ships = self.round_trip("v1_default.yaml")
        self.assert_same_campaign(before, after)
        artemis = ships["Artemis"]
        # Not only in the file: on the ship.
        self.assertEqual(quest_get_state(artemis.id, "cargo_0_0"), 1)
        self.assertEqual(quest_get_state(artemis.id, "side_iron_patrol"), 1)
        self.assertEqual(get_inventory_value(artemis.id, "reputation")["iron"]["nerve"], 25)
        self.assertEqual(get_inventory_value(to_side_id("tsn"), "credits"), 500)
        self.assertEqual(after["current_system"], [2, 1])

    def test_a_story_keeps_its_done_open_and_hidden_steps(self):
        before, after, _ = self.round_trip("v1_story.yaml")
        self.assert_same_campaign(before, after)
        states = {key: quest_get_state(Agent.SHARED_ID, key)
                  for key in ("signal_1", "signal_2", "signal_3")}
        self.assertEqual(states, {"signal_1": 99, "signal_2": 1, "signal_3": 2})

    def test_an_ou_template_mission_comes_back_whole(self):
        before, after, ships = self.round_trip("v1_ou_template.yaml")
        self.assert_same_campaign(before, after)
        self.assertEqual(quest_get_state(Agent.SHARED_ID, "s02_home"), 99)
        self.assertEqual(quest_get_state(Agent.SHARED_ID, "s03_go"), 1)
        self.assertEqual(quest_get_state(Agent.SHARED_ID, "act1_close"), 2)
        self.assertIsNotNone(quest_get(Agent.SHARED_ID, "waypoints/wp_2_2"))
        # A charted location is GENERATED: nothing re-makes it, so it is saved whole.
        self.assertEqual(after["shared_quests"]["waypoints"],
                         before["shared_quests"]["waypoints"])
        self.assertEqual(get_inventory_value(ships["Artemis"].id, "reputation"),
                         {"hollin": {"honesty": 40, "generosity": 40}})
        self.assertEqual(get_inventory_value(to_side_id("tsn"), "credits"), 1150)

    def test_a_second_round_trip_changes_nothing(self):
        self.install("v1_default.yaml")
        self.ship("Artemis")
        self.finish("Continue", self.begin("Continue"))
        once = _read_bytes(self.path)
        self.fn("universe_save_players")()
        self.assertEqual(_read_bytes(self.path), once)


def _boom(data):
    raise ValueError("migration step 1 is broken")


class Safety(SaveHarness):
    """A save that will not load is never written over, and a New Game is a new game."""

    def break_the_ladder(self):
        g = self.module_globals()
        old = g["_MIGRATIONS"]
        g["_MIGRATIONS"] = {1: _boom}
        self.addCleanup(g.__setitem__, "_MIGRATIONS", old)

    def play_an_evening(self, mode, saved):
        """Everything that writes the save during play."""
        self.ship("Artemis")
        self.finish(mode, saved)
        self.fn("universe_save")(7, 3, 3, {"3,3": {"visited": True}})
        self.fn("universe_save_diplomacy")({"tsn|iron": 2})
        self.fn("universe_save_request")()
        self.fn("universe_save_flush")()
        self.fn("universe_save_state")({"universe_seed": 1})

    def test_GAP_11_a_save_that_will_not_migrate_is_left_alone_with_a_copy(self):
        original = self.install("v1_default.yaml")
        self.break_the_ladder()
        saved = self.begin("Continue")
        self.assertIsNone(saved, "the evening still plays, as a new game")
        self.play_an_evening("Continue", saved)
        self.assertEqual(_read_bytes(self.path), original)
        self.assertEqual(_read_bytes(self.path + ".v1.bak"), original)
        self.assertEqual(self.files(), ["universe_save_round_trip_1.yaml",
                                        "universe_save_round_trip_1.yaml.v1.bak"])
        why = self.fn("universe_save_blocked")()
        self.assertIn("could not be loaded", why)
        self.assertIn("migration step 1 is broken", why)
        self.assertIn("universe_save_round_trip_1.yaml.v1.bak", why)
        self.assertIn(why, self.fn("universe_save_report")("Continue"))

    def test_GAP_11_an_unreadable_save_is_left_alone_with_a_copy(self):
        original = self.write_save("players: [unclosed\n  nope: : :\n")
        saved = self.begin("Continue")
        self.assertIsNone(saved)
        self.play_an_evening("Continue", saved)
        self.assertEqual(_read_bytes(self.path), original)
        self.assertEqual(_read_bytes(self.path + ".unreadable.bak"), original)
        self.assertIn("unreadable", self.fn("universe_save_blocked")())

    def test_a_save_from_a_newer_build_is_played_and_not_written_over(self):
        original = self.write_save("save_version: 9\nuniverse_seed: 5\ncurrent_system:\n- 4\n- 4\n")
        saved = self.begin("Continue")
        self.assertEqual(saved["universe_seed"], 5)
        self.play_an_evening("Continue", saved)
        self.assertEqual(_read_bytes(self.path), original)
        self.assertIn("newer build", self.fn("universe_save_blocked")())

    def test_a_write_that_meets_a_broken_file_mid_session_stops_too(self):
        # Not through universe_save_begin: the file goes bad while the game is running.
        self.ship("Artemis")
        self.finish("Continue", self.begin("Continue"))
        original = self.write_save("players: [unclosed\n")
        self.fn("universe_save")(7, 1, 1, {})
        self.fn("universe_save_players")()
        self.assertEqual(_read_bytes(self.path), original)
        self.assertEqual(_read_bytes(self.path + ".unreadable.bak"), original)

    def test_continue_with_no_file_starts_one(self):
        self.assertIsNone(self.begin("Continue"))
        self.ship("Artemis")
        self.finish("Continue", None)
        data = self.fn("universe_load")()
        self.assertEqual(data["save_version"], 2)
        self.assertEqual(list(data["players"]), ["artemis"])
        self.assertEqual(self.fn("universe_save_blocked")(), "")

    def test_GAP_12_a_new_game_does_not_inherit_the_old_diplomacy(self):
        original = self.install("v1_default.yaml")
        self.ship("Artemis")
        self.finish("Continue", self.begin("Continue"))
        self.fn("universe_save_diplomacy")({"tsn|iron": 2})
        self.fn("universe_save_state")(dict(self.fn("universe_load")(), state={"relics": {"a": 1}}))
        old_campaign = _read_bytes(self.path)
        self.launch()                                  # the next launch
        self.ship("Artemis")
        saved = self.begin("New Game")
        self.assertIsNone(saved)
        self.finish("New Game", saved)
        data = self.fn("universe_load")()
        self.assertEqual(data.get("diplomacy", {}), {})
        self.assertNotIn("state", data, "a section this build does not know is the old "
                                        "campaign's too")
        self.assertEqual(data["players"]["artemis"]["quests"], {})
        self.assertEqual(data["current_system"], [0, 0])
        # The campaign that was there is one file away, and so is the version-1 original.
        self.assertEqual(_read_bytes(self.path + ".previous.bak"), old_campaign)
        self.assertEqual(_read_bytes(self.path + ".v1.bak"), original)

    def test_a_new_game_over_a_broken_file_keeps_a_copy_and_saves(self):
        original = self.write_save("players: [unclosed\n")
        self.ship("Artemis")
        self.finish("New Game", self.begin("New Game"))
        self.assertEqual(_read_bytes(self.path + ".previous.bak"), original)
        self.assertEqual(self.fn("universe_save_blocked")(), "")
        self.assertEqual(list(self.fn("universe_load")()["players"]), ["artemis"])


class SaveRequest(SaveHarness):
    """Quest changes ask for a save; one write serves a burst; nothing is written while
    the campaign is still loading."""

    def test_nothing_writes_players_until_the_campaign_is_restored(self):
        original = self.install("v1_default.yaml")
        self.ship("Artemis")
        saved = self.begin("Continue")
        # universe_map_begin has reset the session (setUp did) and has not said ready.
        # The ship is spawned and EMPTY; a save now would write that over its jobs.
        self.assertFalse(self.fn("universe_save_players")())
        self.assertFalse(self.fn("universe_save_flush")())
        self.assertEqual(_read_bytes(self.path), original)
        self.assertTrue(self.fn("universe_save_pending")(), "asked for, not forgotten")
        self.finish("Continue", saved)
        self.assertFalse(self.fn("universe_save_pending")())
        jobs = players_by_name(self.fn("universe_load")())["Artemis"]["quests"]
        self.assertEqual(len(jobs), 17)

    def test_a_burst_of_requests_is_one_write(self):
        self.ship("Artemis")
        self.finish("Continue", self.begin("Continue"))
        self.assertFalse(self.fn("universe_save_flush")(), "nothing asked for")
        g = self.module_globals()
        writes = []
        real = g["_universe_write"]
        g["_universe_write"] = lambda change: writes.append(1) or real(change)
        self.addCleanup(g.__setitem__, "_universe_write", real)
        for _ in range(5):
            self.fn("universe_save_request")()
        self.assertTrue(self.fn("universe_save_flush")())
        self.assertFalse(self.fn("universe_save_flush")())
        self.assertEqual(len(writes), 1)

    def test_a_failed_step_reaches_the_file_without_a_jump(self):
        self.install("v1_default.yaml")
        artemis = self.ship("Artemis")
        self.finish("Continue", self.begin("Continue"))
        quest_set_key(artemis.id, "cargo_0_0", "state", 98)
        quest_set_key(Agent.SHARED_ID, "truce_1", "state", 99)
        self.fn("universe_save_request")()
        self.assertTrue(self.fn("universe_save_flush")())
        data = self.fn("universe_load")()
        self.assertEqual(players_by_name(data)["Artemis"]["quests"]["cargo_0_0"]["state"], 98)
        self.assertEqual(data["shared_quests"]["truce_1"]["state"], 99)

    def test_the_routes_that_ask_are_server_routes(self):
        with open(os.path.join(OU_CORE, "universe.mast"), encoding="utf-8") as f:
            text = f.read()
        for name in ("quest_succeeded", "quest_failed_done", "quest_started"):
            start = text.index("//shared/signal/" + name + " if UNIVERSE_ACTIVE")
            end = text.index("\n\n\n", start) if name == "quest_succeeded" else text.index("\n\n", start)
            self.assertIn("universe_save_request()", text[start:end], name)
            self.assertNotIn("\n//signal/" + name, text)
        # ...and the start sequence is the one these tests drive.
        begin = text.index("=== universe_map_begin")
        order = [text.index(call, begin) for call in (
            "\n    universe_save_reset()", "\n    universe_set_active_save(",
            "\n    saved = universe_save_begin(START_MODE)", "\n    universe_load_players(",
            "\n    universe_save_ready()", "\n    task_schedule(universe_save_loop)")]
        self.assertEqual(order, sorted(order))


class Version2(SaveHarness):
    """Ships are filed under a stable id. Every version-1 fixture climbs the ladder."""

    def test_the_migration_on_each_fixture(self):
        for fixture in FIXTURE_NAMES:
            with self.subTest(fixture):
                shutil.rmtree(os.path.dirname(self.path), ignore_errors=True)
                self.launch()
                original = self.install(fixture)
                v1 = fs.load_yaml_data(self.path)
                self.assertEqual(v1["save_version"], 1)
                v2 = self.fn("universe_load")()
                self.assertEqual(v2["save_version"], 2)
